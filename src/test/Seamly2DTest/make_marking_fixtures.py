"""Generate marking fixtures from current-schema SEAMLY_COPY_FIXTURES outputs."""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET


def marked_pattern(source, draft_ids, diameter):
    """Keep live calculation objects; add private modeling anchors to the first piece."""
    document = ET.parse(source)
    pattern = document.getroot()
    if pattern.findtext("version") not in {"0.7.8", "0.7.9"}:
        raise ValueError(f"{source}: use converted copy-test fixtures, not historical samples")
    pattern.find("version").text = "0.7.9"
    block = pattern.find("draftBlock")
    piece = block.find("pieces").find("piece")
    if piece.find("drillHoles") is not None or piece.find("referenceLines") is not None:
        raise ValueError(f"{source}: source piece already contains markings")
    used_ids = {element.get("id") for element in pattern.iter() if element.get("id")}
    if {"900000", "900001"} & used_ids:
        raise ValueError(f"{source}: reserved test anchor IDs are already used")
    anchors = piece.find("anchors")
    if anchors is None:
        anchors = ET.SubElement(piece, "anchors")
    for anchor, draft_id in zip(("900000", "900001"), draft_ids):
        if not any(point.get("id") == draft_id for point in block.find("calculation").iter("point")):
            raise ValueError(f"{source}: missing live draft point {draft_id}")
        ET.SubElement(block.find("modeling"), "point",
                      {"id": anchor, "idObject": draft_id, "type": "modeling"})
        ET.SubElement(anchors, "record").text = anchor
    holes = ET.SubElement(piece, "drillHoles")
    ET.SubElement(holes, "hole", {"center": "900000", "diameter": diameter})
    lines = ET.SubElement(piece, "referenceLines")
    ET.SubElement(lines, "line", {"start": "900000", "end": "900001", "type": "stripe"})
    ET.SubElement(lines, "line", {"start": "900001", "end": "900000", "type": "plaid"})
    return document, piece


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", required=True, type=Path,
                        help="Directory generated by TST_PatternPieceCopy with SEAMLY_COPY_FIXTURES.")
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    individual, piece = marked_pattern(args.input_dir / "male_shirt-copied.sm2d", ("1", "2"), "0.2")
    for name, flip in (("original", "None"), ("horizontal", "Horizontal"),
                       ("vertical", "Vertical"), ("both", "Both")):
        piece.set("flip", flip)
        individual.write(args.output_dir / f"marked-{name}.sm2d", encoding="UTF-8", xml_declaration=True)
    multisize, _ = marked_pattern(args.input_dir / "jacket1_52-176-copied.sm2d", ("34", "33"), "2.0")
    multisize.write(args.output_dir / "marked-multisize.sm2d", encoding="UTF-8", xml_declaration=True)


if __name__ == "__main__":
    main()
