#!/bin/bash
#******************************************************************************
# **  @file   version.sh
# **  @author slspencer
# **
# **  @brief
# **  Writes the build version into src/libs/vmisc/project_version_number.h.
# **
# **  Usage: ./packaging/version.sh 26.9.2317
# **
# **  The version is YY.M.DDHH. DDHH is day * 100 + hour (0-23), because the
# **  MSI ProductVersion has only three fields.
# **  Git ignores the header, so a build does not change tracked files.
# **  Readers of the header:
# **    - projectversion.h/.cpp: the app version and the Windows resource version.
# **    - common.pri: VERSION for the macOS Info.plist files.
# **    - SeamlyLayout CMakeLists.txt: the suite version.
# **  A build without this script gets 0.0.0 from common.pri.
# **
# ** @copyright
# **  Copyright (C) 2026 Seamly2D Project
# **
# **  @license
# **  GPL-3.0-or-later
#******************************************************************************

if [ $# -eq 1 ]; then
    VERSIONSTR="${1}"
else
    echo "usage: $0 <version>, where version needs to be a 3 part version number, eg. 26.9.2317"
    exit 1
fi

VERSIONARR=(${VERSIONSTR//./ })

if [ ${#VERSIONARR[@]} -ne 3 ]; then
    echo "error: '${VERSIONSTR}' is not a 3 part version number, eg. 26.9.2317"
    exit 1
fi

# The header holds C++ integer literals. A leading zero makes an octal literal:
# 26.8.0105 fails to compile, and 048 becomes 39. '10#' forces base 10.
for i in "${!VERSIONARR[@]}"; do
    if ! [[ ${VERSIONARR[$i]} =~ ^[0-9]+$ ]]; then
        echo "error: version component '${VERSIONARR[$i]}' is not a number"
        exit 1
    fi
    VERSIONARR[$i]=$((10#${VERSIONARR[$i]}))
done

VERSIONSTR="${VERSIONARR[0]}.${VERSIONARR[1]}.${VERSIONARR[2]}"

echo "setting version to"
echo "major: ${VERSIONARR[0]}"
echo "minor: ${VERSIONARR[1]}"
echo "day and hour: ${VERSIONARR[2]}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HEADER="${SCRIPT_DIR}/../src/libs/vmisc/project_version_number.h"

# Keep this layout in step with the default that common.pri writes.
cat > "${HEADER}" <<EOF
// Generated by packaging/version.sh. Do not edit. Git ignores this file.
#ifndef PROJECT_VERSION_NUMBER_H
#define PROJECT_VERSION_NUMBER_H

#define PROJECT_VERSION_MAJOR ${VERSIONARR[0]}
#define PROJECT_VERSION_MINOR ${VERSIONARR[1]}
#define PROJECT_VERSION_DAY_HOUR ${VERSIONARR[2]}
#define PROJECT_VERSION_STR "${VERSIONSTR}"

#endif // PROJECT_VERSION_NUMBER_H
EOF
echo "wrote ${HEADER}"
